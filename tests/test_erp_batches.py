def test_trade_flow_references_snapshot_reveal_and_fees(db):
    buyer, seller = _buyer_seller(db)
    rfq = rfq_service.create_rfq(db, buyer.company, RFQRequest(
        mineral_type="Limestone", quantity_value=Decimal("100"), quantity_unit="MT",
        delivery_location="Riyadh", delivery_timeframe="2 weeks"), created_by=buyer)
    assert rfq.rfq_reference and rfq.rfq_reference.startswith("RFQ-") and rfq.closes_at is not None
    q = quotation_service.submit_quotation(db, rfq, seller.company, QuotationRequest(
        price_value=Decimal("123.45"), lead_time_days=5), submitted_by=seller)
    assert q.quotation_reference.startswith("QUO-") and q.total_price == Decimal("12345.00") and q.valid_until
    order = order_service.accept_quotation(db, rfq, q, buyer.company)
    vat = Decimal(ss.get_setting(db, "vat_rate_pct"))
    assert order.order_reference.startswith("ORD-")
    assert order.subtotal_sar == Decimal("12345.00")
    assert order.vat_amount_sar == (Decimal("12345.00") * vat / 100).quantize(Decimal("0.01"))
    assert order.total_value_sar == order.subtotal_sar + order.vat_amount_sar
    assert order.identity_revealed_at is None
    order = order_service.confirm_order(db, order, confirmed_by=seller)
    assert order.identity_revealed_at is not None
    assert db.query(RevealLog).filter_by(order_id=order.id).count() == 1
    parties = {f.party: f for f in order.settlement_fees}
    assert set(parties) == {"buyer", "seller"}
    assert parties["buyer"].total_sar == parties["buyer"].amount_sar + parties["buyer"].vat_amount_sar


def test_competing_quotes_rejected_on_accept(db):
    from app.models.quotation import Quotation
    buyer, seller = _buyer_seller(db)
    rfq = rfq_service.create_rfq(db, buyer.company, RFQRequest(
        mineral_type="Silica", quantity_value=Decimal("10"), delivery_location="Jubail", delivery_timeframe="1 month"))
    q1 = quotation_service.submit_quotation(db, rfq, seller.company, QuotationRequest(price_value=Decimal("50"), lead_time_days=3))
    other_seller_company = db.query(Company).filter(Company.role == seller.company.role, Company.id != seller.company_id,
                                                    Company.status == ApprovalStatus.APPROVED).first()
    if other_seller_company is None:
        return  # seed has a single seller — nothing to compete
    q2 = quotation_service.submit_quotation(db, rfq, other_seller_company, QuotationRequest(price_value=Decimal("55"), lead_time_days=3))
    order_service.accept_quotation(db, rfq, q1, buyer.company)
    db.expire_all()
    assert db.get(Quotation, q2.id).status == QuotationStatus.REJECTED


def test_founding_member_fee_waiver(db, admin):
    buyer, seller = _buyer_seller(db)
    ss.set_setting(db, "waive_fees_founding_members", True)
    seller.company.is_founding_member = True
    db.commit()
    try:
        rfq = rfq_service.create_rfq(db, buyer.company, RFQRequest(
            mineral_type="Kaolin", quantity_value=Decimal("1"), delivery_location="Dammam", delivery_timeframe="now"))
        q = quotation_service.submit_quotation(db, rfq, seller.company, QuotationRequest(price_value=Decimal("10"), lead_time_days=1))
        order = order_service.confirm_order(db, order_service.accept_quotation(db, rfq, q, buyer.company))
        fees = {f.party: f.status for f in order.settlement_fees}
        assert fees["seller"] == SettlementFeeStatus.WAIVED
        assert fees["buyer"] == (SettlementFeeStatus.WAIVED if buyer.company.is_founding_member else SettlementFeeStatus.PENDING)
    finally:
        ss.set_setting(db, "waive_fees_founding_members", False)
        seller.company.is_founding_member = False
        db.commit()


