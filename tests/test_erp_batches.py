def test_subscription_limit_enforced_when_enabled(db):
    from app.core import system_settings as ss
    from app.models.md_commercial import SubscriptionPlan
    from app.services.rfq_service import RFQActionError
    buyer, _ = _buyer_seller(db)
    tier = buyer.company.subscription_tier
    if tier is None:
        return
    plan = db.query(SubscriptionPlan).filter_by(code=tier.value).one()
    old_limit = plan.max_active_rfqs
    plan.max_active_rfqs = 0
    ss.set_setting(db, "enforce_subscription_limits", True)
    db.commit()
    try:
        import pytest
        with pytest.raises(RFQActionError):
            rfq_service.create_rfq(db, buyer.company, RFQRequest(
                mineral_type="Any", quantity_value=Decimal("1"), delivery_location="x", delivery_timeframe="y"))
    finally:
        db.rollback()
        plan = db.query(SubscriptionPlan).filter_by(code=tier.value).one()
        plan.max_active_rfqs = old_limit
        ss.set_setting(db, "enforce_subscription_limits", False)
        db.commit()
