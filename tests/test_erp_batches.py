def test_batch_qc_fail_rejects_and_blocks_release(admin, db):
    batch = db.query(Batch).filter_by(batch_number="LOT-2026-00125").one()
    # reset to quarantine and record an out-of-spec SiO2 value (spec ≤ 2 %)
    admin.post(f"/admin/batches/{batch.id}/status", {"status": "quarantine"})  # refused? only release is gated
    from app.models.md_quality import QualityParameter
    sio2 = db.query(QualityParameter).filter_by(code="SIO2").one()
    admin.post(f"/admin/batches/{batch.id}/results", {"parameter_id": str(sio2.id), "measured_value": "3.4"})
    db.expire_all()
    b = db.get(Batch, batch.id)
    assert b.qc_status == QCStatus.FAILED and b.status == BatchStatus.REJECTED
    r = admin.post(f"/admin/batches/{batch.id}/status", {"status": "released"})
    assert "error=" in r.headers["location"]
    # fix the value → passes again; with auto-release only QUARANTINE batches move, so re-quarantine first
    admin.post(f"/admin/batches/{batch.id}/status", {"status": "quarantine"})
    admin.post(f"/admin/batches/{batch.id}/results", {"parameter_id": str(sio2.id), "measured_value": "1.2"})
    db.expire_all()
    b = db.get(Batch, batch.id)
    assert b.qc_status == QCStatus.PASSED and b.status == BatchStatus.RELEASED

