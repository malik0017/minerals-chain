def test_master_data_crud_toggle_delete(admin, db, uniq):
    code = f"TG{uniq}"
    r = admin.post("/admin/master-data/mineral-groups/new",
                   {"code": code.lower(), "name_en": "Test group", "name_ar": "مجموعة", "sort_order": "5", "is_active": "1"})
    assert r.status_code == 303 and "error" not in r.headers["location"]
    row = db.query(MineralGroup).filter_by(code=code).one()           # code upper-cased
    r = admin.post(f"/admin/master-data/mineral-groups/{row.id}/edit",
                   {"code": code, "name_en": "Renamed", "sort_order": "5", "is_active": "1"})
    assert r.status_code == 303
    db.expire_all()
    assert db.get(MineralGroup, row.id).name_en == "Renamed"
    admin.post(f"/admin/master-data/mineral-groups/{row.id}/toggle")
    db.expire_all()
    assert db.get(MineralGroup, row.id).is_active is False
    r = admin.post(f"/admin/master-data/mineral-groups/{row.id}/delete")
    assert "msg=" in r.headers["location"]
    row_id = row.id
    db.expunge_all()
    assert db.query(MineralGroup).filter_by(id=row_id).first() is None


